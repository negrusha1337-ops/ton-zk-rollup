import { toNano } from '@ton/core';

// Суммы сообщений для прогона rollup-контракта в testnet. Тесты на настоящем контракте
// отправляют те же суммы в Sandbox: если их перестанет хватать на газ, это всплывёт до запуска
// в сети. Расход шагов протокола v2 измерен на настоящем контракте: фиксация ключа — на ключе
// программы EVM (tests/RollupKeys.spec.ts), батч — на пруфах игрушечной схемы под дайджест из
// одиннадцати слов (tests/RollupProof.spec.ts). На пруфах SP1 протокола v2 батч ещё не мерился.
//
// Всё, что приложено к сообщению и не потрачено на газ, остаётся на контракте, а вернуть
// оттуда монеты нечем (управления у контракта нет). Поэтому суммы взяты примерно вдвое
// выше измеренного расхода, не больше. Цена газа — 66,67 нанотон (конфиг сети, параметр 21);
// расход — из bench/rollup-key-gas.json, bench/rollup-submit-batch.json и
// bench/rollup-payout-gas.json.

/** Развёртывание: остаётся на контракте как запас на хранение (ключ — около 3 000 ячеек). */
export const DEPLOY_VALUE = toNano('0.05');
/** Часть ключа: до 7 233 gas, около 0,0005 TON. */
export const KEY_PART_VALUE = toNano('0.001');
/** Фиксация ключа: 23 982 gas, около 0,0014 TON. */
export const KEY_FINALIZE_VALUE = toNano('0.003');
/** Порция данных батча: около 5 200 gas (0,00035 TON) при любом размере порции. */
export const PUBLISH_DATA_VALUE = toNano('0.001');
/**
 * Батч: 950–954,7 тыс. gas на пруфах игрушечной схемы, наибольший — на словаре очереди,
 * заполненном до предела, с четырьмя записями в словаре данных (bench/rollup-submit-batch.json);
 * сумма покрывает полный лимит
 * транзакции 1 млн gas (0,0667 TON при нынешней цене).
 */
export const SUBMIT_BATCH_VALUE = toNano('0.072');
/**
 * Вывод: контракт сам считает минимум из газа по ценам сети (get-метод minimumValues,
 * около 0,011 TON при нынешних ценах). Скрипт прогона берёт минимум у контракта; эта сумма —
 * для тестов и как верхняя граница.
 */
export const WITHDRAW_VALUE = toNano('0.02');

/** Срок аварийного выхода: сколько депозит может ждать обработки до заморозки rollup'а. */
export const ESCAPE_TIMEOUT_SECONDS = 7 * 24 * 3600;
/**
 * Наибольший возраст блока L2 на момент приёма батча: сутки. Пруф блока на ноутбуке строится
 * около четверти часа, так что на пруф и приём батча остаётся большой запас; контракт допускает
 * от получаса до срока заморозки.
 */
export const MAX_BLOCK_AGE_SECONDS = 24 * 3600;
/**
 * Возраст блока для стенда в testnet: наименьший, с которым контракт фиксирует ключ (полчаса).
 * Батч с блоком принимается, только пока время L1 — в пределах этого срока после времени блока.
 */
export const TESTNET_MAX_BLOCK_AGE_SECONDS = 1800;
/**
 * Срок аварийного выхода для стенда в testnet: наименьший, с которым контракт соглашается
 * зафиксировать ключи (MIN_ESCAPE_TIMEOUT в contracts/rollup/logic.tolk). Прогон аварийного
 * пути поэтому ждёт час; скрипт прогона продолжает с места остановки.
 */
export const TESTNET_ESCAPE_TIMEOUT_SECONDS = 3600;
/** Заморозка (около 4 800 gas), возврат депозита (около 7 000 gas), выплата долга, сброс данных. */
export const ESCAPE_SERVICE_VALUE = toNano('0.002');
/** Депозит, который в прогоне testnet остаётся необработанным и запускает срок заморозки. */
export const LATE_DEPOSIT_VALUE = toNano('0.06');
/**
 * Принудительная транзакция L2: контракт берёт плату 0,05 TON; сверху — газ постановки в
 * очередь: до 36,3 тыс. gas на транзакции наибольшей длины при полном словаре очереди
 * (bench/rollup-queue-gas.json), около 0,0024 TON при цене газа 66,67 нанотон.
 */
export const FORCE_TRANSACTION_VALUE = toNano('0.055');
